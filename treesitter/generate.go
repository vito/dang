package main

import (
	"crypto/sha256"
	"encoding/json"
	"fmt"
	"os"
	"path/filepath"

	"github.com/vito/dang/v2/pkg/dang"
)

//go:generate go run .

//go:generate tree-sitter generate src/grammar.json

//go:generate go run . -stamp

func main() {
	if len(os.Args) > 1 && os.Args[1] == "-stamp" {
		if err := stampDanglang(); err != nil {
			panic(err)
		}
		return
	}

	grammarFile, err := os.Create("src/grammar.json")
	if err != nil {
		panic(err)
	}
	defer grammarFile.Close() //nolint:errcheck

	enc := json.NewEncoder(grammarFile)
	enc.SetIndent("", "  ")
	enc.Encode(dang.TreesitterGrammar()) //nolint:errcheck
}

// danglangSources are the C files pkg/dang/danglang compiles by #include.
var danglangSources = []string{
	"src/parser.c",
	"src/scanner.c",
	"src/tree_sitter/alloc.h",
	"src/tree_sitter/array.h",
	"src/tree_sitter/parser.h",
}

// stampDanglang records a digest of danglangSources in a Go file of the
// danglang package. Go's build cache doesn't track files a cgo package
// #includes from another directory, so without it a regenerated parser.c
// could be silently skipped in favor of a cached build of the old one.
func stampDanglang() error {
	h := sha256.New()
	for _, path := range danglangSources {
		content, err := os.ReadFile(path)
		if err != nil {
			return err
		}
		fmt.Fprintf(h, "%s %d\n", path, len(content))
		h.Write(content)
	}
	src := fmt.Sprintf(`// Code generated by treesitter/generate.go; DO NOT EDIT.

package danglang

// sourcesDigest is a SHA-256 of the treesitter/src files this package
// #includes. Go's build cache doesn't track them, so this changing is what
// makes Go rebuild the package when the grammar is regenerated.
const sourcesDigest = %q
`, fmt.Sprintf("%x", h.Sum(nil)))
	return os.WriteFile(filepath.Join("..", "pkg", "dang", "danglang", "sources_digest.go"), []byte(src), 0o644)
}
